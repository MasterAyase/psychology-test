// 恋爱依恋风格测试。基于成人依恋的"焦虑-回避"两维度模型，题目为本站原创。
window.PT_TESTS = window.PT_TESTS || [];

(function () {
  const items = [
    ['对方回消息慢了，我会忍不住胡思乱想', 'A', 1],
    ['我很少担心对方会离开我', 'A', -1],
    ['我常常需要对方确认他/她是爱我的', 'A', 1],
    ['吵架后，我会担心这段关系就此结束', 'A', 1],
    ['即使对方很忙顾不上我，我也能安心做自己的事', 'A', -1],
    ['我担心自己在对方心里没有那么重要', 'A', 1],
    ['对方和异性朋友走得近，我会很不安', 'A', 1],
    ['我相信自己值得被好好爱着', 'A', -1],
    ['对方想和我非常亲密时，我会有点想后退', 'V', 1],
    ['我愿意向伴侣倾诉自己的脆弱和烦恼', 'V', -1],
    ['遇到困难时，我更习惯自己扛', 'V', 1],
    ['依赖伴侣让我觉得很自然、很舒服', 'V', -1],
    ['我需要在关系里保留很多属于自己的空间', 'V', 1],
    ['谈论彼此的感受对我来说并不难', 'V', -1],
    ['关系发展得太快，会让我想踩刹车', 'V', 1],
    ['我能自然地向对方表达"我需要你"', 'V', -1]
  ].map(([t, d, k]) => ({ t, d, k }));

  const STYLES = {
    secure: {
      title: '安全型',
      summary: '你在亲密关系中比较放松：既能信任对方、表达需要，也能接受彼此有独立的空间。',
      tips: '继续保持坦诚沟通。当伴侣不安时，你的稳定本身就是很好的支持。'
    },
    anxious: {
      title: '焦虑型',
      summary: '你非常投入关系，对伴侣的态度变化很敏感，有时会担心不被爱或被冷落。',
      tips: '试着把"猜测"换成"直接问"。在关系之外也培养能给你安全感的爱好和朋友。'
    },
    avoidant: {
      title: '回避型',
      summary: '你重视独立和个人空间，习惯自己处理情绪，太紧密的依赖会让你不自在。',
      tips: '可以从小事开始练习分享感受。告诉伴侣你需要空间的原因，能减少对方的误解。'
    },
    fearful: {
      title: '矛盾型',
      summary: '你渴望亲密，又害怕靠得太近会受伤，常在"想靠近"和"想逃开"之间摇摆。',
      tips: '留意自己什么时候想靠近、什么时候想退开，把规律说给信任的人听。必要时可以寻求心理咨询的帮助。'
    }
  };

  window.PT_TESTS.push({
    id: 'attachment',
    name: '恋爱依恋风格',
    short: '看看你在亲密关系里，对"被抛弃的担心"和"对亲密的回避"各有多少。',
    minutes: 3,
    kind: 'likert',
    basis: '成人依恋两维度模型，本站原创题目',
    intro: [
      '心理学研究常用两个维度描述成年人在亲密关系中的模式：依恋焦虑（担心被冷落、需要确认）和依恋回避（不习惯依赖、需要距离）。',
      '请想着你的现任或最近一段感情作答；如果没有恋爱经历，就想象你在亲密关系中通常的样子。'
    ],
    items,
    score(answers) {
      const p = PT.dimPercent(items, answers);
      const hiA = p.A > 50;
      const hiV = p.V > 50;
      const key = hiA ? (hiV ? 'fearful' : 'anxious') : hiV ? 'avoidant' : 'secure';
      const s = STYLES[key];
      return {
        title: s.title,
        summary: s.summary,
        bars: [
          { label: '依恋焦虑', value: p.A, note: hiA ? '你对关系中的不确定比较敏感。' : '你对关系有比较稳定的信心。' },
          { label: '依恋回避', value: p.V, note: hiV ? '你更习惯保持一定的距离和独立。' : '你能比较自在地亲近和依赖对方。' }
        ],
        sections: [
          { h: '相处建议', p: s.tips },
          { h: '依恋风格会变吗', p: '会。依恋风格受早期经历影响，但一段稳定、被理解的关系，或者有意识的自我觉察，都能让人慢慢变得更有安全感。' }
        ]
      };
    }
  });
})();
